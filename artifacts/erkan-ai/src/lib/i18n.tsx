type TranslationDict = typeof translations.syrian;

interface LanguageContextType {
  locale: Locale;
  setLocale: (l: Locale) => void;
  t: (key: keyof TranslationDict, params?: Record<string, string | number>) => string;
  formatDate: (iso: string | null | undefined) => string;
  formatTime: (iso: string) => string;
  syncUserCountry: (country: string) => void;
}

const LanguageContext = createContext<LanguageContextType | null>(null);

export function useLang() {
  const ctx = useContext(LanguageContext);
  if (!ctx) throw new Error("useLang must be used within LanguageProvider");
  return ctx;
}

export function LanguageProvider({ children }: { children: React.ReactNode }) {
  const [locale, setLocale] = useState<Locale>(() => {
    const saved = localStorage.getItem("erkan_locale");
    const supportedLocales = ["syrian", "egyptian", "saudi", "jordanian", "turkish"];
    if (saved && supportedLocales.includes(saved)) {
      return saved as Locale;
    }
    return "syrian";
  });

  const syncUserCountry = useCallback((country: string) => {
    const existing = localStorage.getItem("erkan_locale");
    if (!existing && country) {
      const matchingLocale = countryToLocale[country];
      if (matchingLocale && matchingLocale !== locale) {
        setLocale(matchingLocale);
        localStorage.setItem("erkan_locale", matchingLocale);
      }
    }
  }, [locale]);

  useEffect(() => {
    document.documentElement.dir = locale === "turkish" ? "ltr" : "rtl";
    document.documentElement.lang = locale === "turkish" ? "tr" : "ar";
  }, [locale]);

  const t = useCallback((key: keyof TranslationDict, params?: Record<string, string | number>) => {
    const dict = translations[locale] || translations.syrian;
    let str = (dict as any)[key] || (translations.syrian as any)[key] || String(key);
    if (params) {
      Object.keys(params).forEach(k => {
        str = str.replace(`{${k}}`, String(params[k]));
      });
    }
    return str;
  }, [locale]);

  const formatDate = useCallback((iso: string | null | undefined) => {
    if (!iso) return "—";
    return new Date(iso).toLocaleDateString(locale === "turkish" ? "tr-TR" : "ar-SA", { year: "numeric", month: "long", day: "numeric" });
  }, [locale]);

  const formatTime = useCallback((iso: string) => {
    return new Date(iso).toLocaleTimeString(locale === "turkish" ? "tr-TR" : "ar-SA", { hour: "2-digit", minute: "2-digit" });
  }, [locale]);

  return (
    <LanguageContext.Provider value={{ locale, setLocale, t, formatDate, formatTime, syncUserCountry }}>
      {children}
    </LanguageContext.Provider>
  );
}
